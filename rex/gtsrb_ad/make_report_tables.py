#!/usr/bin/env python3
"""Generate the results tables for report.md from the produced artifacts.

Keeps the report's numbers derived rather than hand-copied.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
NA = Path("/Users/labbaf/Documents/rex/neuron_activations")
MODELS = ["gtsrb_a", "gtsrb_b", "gtsrb_c", "gtsrb_d", "gtsrb_e"]
GAMMA = "0.5"


def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def models_table():
    man = HERE / "models" / "manifest.csv"
    rows = []
    for r in csv.DictReader(man.open()):
        rows.append([r["name"], r["arch"], f"{int(r['relu_neurons']):,}",
                     f"{int(r['params']):,}", r["test_acc"], r["onnx_rel_diff"]])
    return md_table(["model", "architecture", "ReLU neurons", "params",
                     "test acc", "ONNX rel. diff"], rows)


def explanations_table():
    rows = []
    for m in MODELS:
        p = HERE / "out" / f"{m}_ad_g{GAMMA}_sizes.csv"
        if not p.exists():
            continue
        recs = list(csv.DictReader(p.open()))
        ok = [r for r in recs if r["status"] == "ok"]
        if not ok:
            rows.append([m, len(recs), 0, "-", "-", "-", "-"])
            continue
        areas = [int(r["area_px"]) for r in ok]
        confs = [float(r["conf"]) for r in ok if r["conf"]]
        secs = [float(r["secs"]) for r in ok]
        rows.append([
            m, len(recs), len(ok),
            f"{sum(areas)/len(areas):.1f}",
            f"{sum(areas)/len(areas)/1024:.1%}",
            f"{min(areas)}-{max(areas)}",
            f"{sum(confs)/len(confs):.3f}" if confs else "-",
            f"{sum(secs)/len(secs):.1f}",
        ])
    return md_table(["model", "samples", "explained", "mean size (px)",
                     "mean size (%)", "min-max px", "mean conf", "mean s/img"], rows)


def neurons_table():
    rows = []
    for m in MODELS:
        p = NA / f"{m}_ad_meta.json"
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        rows.append([
            m, d["n_hidden_layers"], str(d["hidden_sizes"]),
            f"{d['total_relu_neurons']:,}", d["n_samples"],
            f"{d['mean_deactive_total']:.0f}",
            f"{d['frac_deactive']:.1%}",
            ", ".join(f"{v:.0f}" for v in d["mean_deactive_per_layer"]),
        ])
    return md_table(["model", "hidden layers", "layer sizes", "total ReLU",
                     "samples", "mean deactive", "% deactive",
                     "per-layer deactive"], rows)


def main():
    parts = [
        "<!-- generated by make_report_tables.py -->",
        "### Models\n", models_table(),
        "\n### Explanations (ReX + ConvAD, gamma=0.5)\n", explanations_table(),
        "\n### AD neuron deactivation\n", neurons_table(),
    ]
    text = "\n".join(parts) + "\n"
    (HERE / "report_tables.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
